CREATE TABLE brand_info (
    BRAND_NO BIGINT NOT NULL AUTO_INCREMENT,
    BRAND_NAME_KO VARCHAR(100) NOT NULL,
    BRAND_NAME_EN VARCHAR(100) NULL,
    BRAND_COUNTRY VARCHAR(100) NULL,
    BRAND_LOGO_IMAGE_URL VARCHAR(1000) NULL,
    DISPLAY_YN CHAR(1) NOT NULL DEFAULT 'Y',
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    UPDT_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDT_ID VARCHAR(30) NOT NULL,
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (BRAND_NO),
    UNIQUE KEY UK_BRAND_INFO_NAME_KO (BRAND_NAME_KO)
);

CREATE TABLE category_info (
    CATEGORY_NO BIGINT NOT NULL AUTO_INCREMENT,
    CATEGORY_NAME VARCHAR(100) NOT NULL,
    CATEGORY_DEPTH INT NOT NULL DEFAULT 1,
    PARENT_CATEGORY_NO BIGINT NULL,
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DISPLAY_YN CHAR(1) NOT NULL DEFAULT 'Y',
    UPDT_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDT_ID VARCHAR(30) NOT NULL,
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (CATEGORY_NO),
    KEY IX_CATEGORY_INFO_PARENT_NO (PARENT_CATEGORY_NO),
    CONSTRAINT FK_CATEGORY_INFO_PARENT_NO FOREIGN KEY (PARENT_CATEGORY_NO) REFERENCES category_info (CATEGORY_NO)
);

CREATE TABLE goods_info (
    GOODS_NO BIGINT NOT NULL AUTO_INCREMENT,
    GOODS_CODE VARCHAR(50) NOT NULL,
    GOODS_NAME_KO VARCHAR(200) NOT NULL,
    GOODS_NAME_EN VARCHAR(200) NULL,
    BRAND_NO BIGINT NULL,
    CATEGORY_NO BIGINT NOT NULL,
    SELLER_NAME VARCHAR(100) NOT NULL,
    MANUFACTURER VARCHAR(100) NULL,
    ORIGIN_COUNTRY VARCHAR(100) NULL,
    COST_PRICE DECIMAL(15, 2) NOT NULL DEFAULT 0,
    SALE_PRICE DECIMAL(15, 2) NOT NULL DEFAULT 0,
    DISCOUNT_PRICE DECIMAL(15, 2) NULL,
    STOCK_QUANTITY INT NOT NULL DEFAULT 0,
    SAFETY_STOCK_QUANTITY INT NOT NULL DEFAULT 0,
    TAX_TYPE VARCHAR(20) NOT NULL DEFAULT 'TAXABLE',
    SHIPPING_TYPE VARCHAR(20) NOT NULL DEFAULT 'FREE',
    SHIPPING_FEE DECIMAL(15, 2) NOT NULL DEFAULT 0,
    GOODS_STATUS VARCHAR(30) NOT NULL DEFAULT 'READY',
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DISPLAY_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DISPLAY_START_DATE DATETIME NULL,
    DISPLAY_END_DATE DATETIME NULL,
    SHORT_DESCRIPTION VARCHAR(500) NULL,
    DETAIL_DESCRIPTION TEXT NULL,
    SEARCH_KEYWORDS VARCHAR(500) NULL,
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID VARCHAR(30) NOT NULL,
    UPDT_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDT_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (GOODS_NO),
    UNIQUE KEY UK_GOODS_INFO_CODE (GOODS_CODE),
    KEY IX_GOODS_INFO_BRAND_NO (BRAND_NO),
    KEY IX_GOODS_INFO_CATEGORY_NO (CATEGORY_NO),
    CONSTRAINT FK_GOODS_INFO_BRAND_NO FOREIGN KEY (BRAND_NO) REFERENCES brand_info (BRAND_NO),
    CONSTRAINT FK_GOODS_INFO_CATEGORY_NO FOREIGN KEY (CATEGORY_NO) REFERENCES category_info (CATEGORY_NO)
);

CREATE TABLE goods_image (
    GOODS_IMAGE_NO BIGINT NOT NULL AUTO_INCREMENT,
    GOODS_NO BIGINT NOT NULL,
    IMAGE_URL VARCHAR(1000) NOT NULL,
    ORIGINAL_FILE_NAME VARCHAR(255) NOT NULL,
    REPRESENTATIVE_YN CHAR(1) NOT NULL DEFAULT 'N',
    SORT_ORDER INT NOT NULL DEFAULT 0,
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (GOODS_IMAGE_NO),
    KEY IX_GOODS_IMAGE_GOODS_NO (GOODS_NO),
    CONSTRAINT FK_GOODS_IMAGE_GOODS_NO FOREIGN KEY (GOODS_NO) REFERENCES goods_info (GOODS_NO)
);
