-- 로컬 DB 전용. 자동 실행하지 않는다. 운영 적용은 별도 승인 대상이다.
CREATE TABLE IF NOT EXISTS goods_info_history (
    GOODS_INFO_HISTORY_NO BIGINT NOT NULL AUTO_INCREMENT,
    GOODS_NO BIGINT NOT NULL,
    CHANGE_TYPE VARCHAR(20) NOT NULL,
    BEFORE_VALUES JSON NULL,
    AFTER_VALUES JSON NOT NULL,
    CHANGED_FIELDS JSON NOT NULL,
    REG_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    REG_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (GOODS_INFO_HISTORY_NO),
    KEY IX_GOODS_INFO_HISTORY_GOODS (GOODS_NO, GOODS_INFO_HISTORY_NO),
    CONSTRAINT FK_GOODS_INFO_HISTORY_GOODS FOREIGN KEY (GOODS_NO) REFERENCES goods_info (GOODS_NO)
);

CREATE TABLE IF NOT EXISTS goods_price_history (
    GOODS_PRICE_HISTORY_NO BIGINT NOT NULL AUTO_INCREMENT,
    GOODS_INFO_HISTORY_NO BIGINT NOT NULL,
    GOODS_NO BIGINT NOT NULL,
    CHANGE_TYPE VARCHAR(20) NOT NULL,
    BEFORE_COST_PRICE DECIMAL(15, 2) NULL,
    AFTER_COST_PRICE DECIMAL(15, 2) NOT NULL,
    BEFORE_SALE_PRICE DECIMAL(15, 2) NULL,
    AFTER_SALE_PRICE DECIMAL(15, 2) NOT NULL,
    BEFORE_DISCOUNT_PRICE DECIMAL(15, 2) NULL,
    AFTER_DISCOUNT_PRICE DECIMAL(15, 2) NULL,
    REG_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    REG_ID VARCHAR(30) NOT NULL,
    PRIMARY KEY (GOODS_PRICE_HISTORY_NO),
    UNIQUE KEY UK_GOODS_PRICE_HISTORY_INFO (GOODS_INFO_HISTORY_NO),
    KEY IX_GOODS_PRICE_HISTORY_GOODS (GOODS_NO, GOODS_PRICE_HISTORY_NO),
    CONSTRAINT FK_GOODS_PRICE_HISTORY_INFO FOREIGN KEY (GOODS_INFO_HISTORY_NO) REFERENCES goods_info_history (GOODS_INFO_HISTORY_NO),
    CONSTRAINT FK_GOODS_PRICE_HISTORY_GOODS FOREIGN KEY (GOODS_NO) REFERENCES goods_info (GOODS_NO)
);

-- 기존 상품의 현재 상태를 초기 기준으로 보존한다. 과거 변경 내역을 복원하는 것은 아니다.
INSERT INTO goods_info_history (GOODS_NO, CHANGE_TYPE, BEFORE_VALUES, AFTER_VALUES, CHANGED_FIELDS, REG_DATE, REG_ID)
SELECT P.GOODS_NO, 'INITIAL', NULL, JSON_OBJECT(
    'goodsCode', P.GOODS_CODE,
    'goodsNameKo', P.GOODS_NAME_KO,
    'goodsNameEn', P.GOODS_NAME_EN,
    'brandNo', P.BRAND_NO,
    'categoryNo', P.CATEGORY_NO,
    'sellerName', P.SELLER_NAME,
    'manufacturer', P.MANUFACTURER,
    'originCountry', P.ORIGIN_COUNTRY,
    'stockQuantity', P.STOCK_QUANTITY,
    'safetyStockQuantity', P.SAFETY_STOCK_QUANTITY,
    'taxType', P.TAX_TYPE,
    'shippingType', P.SHIPPING_TYPE,
    'shippingFee', P.SHIPPING_FEE,
    'goodsStatus', P.GOODS_STATUS,
    'useYn', P.USE_YN,
    'displayYn', P.DISPLAY_YN,
    'displayStartDate', DATE_FORMAT(P.DISPLAY_START_DATE, '%Y-%m-%dT%H:%i:%s'),
    'displayEndDate', DATE_FORMAT(P.DISPLAY_END_DATE, '%Y-%m-%dT%H:%i:%s'),
    'shortDescription', P.SHORT_DESCRIPTION,
    'detailDescription', P.DETAIL_DESCRIPTION,
    'searchKeywords', P.SEARCH_KEYWORDS
), JSON_ARRAY(), NOW(6), P.UPDT_ID
FROM goods_info P WHERE NOT EXISTS (SELECT 1 FROM goods_info_history H WHERE H.GOODS_NO = P.GOODS_NO);

INSERT INTO goods_price_history (GOODS_INFO_HISTORY_NO, GOODS_NO, CHANGE_TYPE,
    BEFORE_COST_PRICE, AFTER_COST_PRICE, BEFORE_SALE_PRICE, AFTER_SALE_PRICE,
    BEFORE_DISCOUNT_PRICE, AFTER_DISCOUNT_PRICE, REG_DATE, REG_ID)
SELECT H.GOODS_INFO_HISTORY_NO, P.GOODS_NO, 'INITIAL', NULL, P.COST_PRICE, NULL, P.SALE_PRICE,
    NULL, P.DISCOUNT_PRICE, NOW(6), P.UPDT_ID
FROM goods_info P JOIN goods_info_history H ON H.GOODS_NO = P.GOODS_NO AND H.CHANGE_TYPE = 'INITIAL'
WHERE NOT EXISTS (SELECT 1 FROM goods_price_history PH WHERE PH.GOODS_NO = P.GOODS_NO);

