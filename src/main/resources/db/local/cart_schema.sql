-- Apply only to the local development database after checking parent column types.
CREATE TABLE IF NOT EXISTS cart_item (
    USER_NO INT NOT NULL,
    GOODS_NO BIGINT NOT NULL,
    QUANTITY INT NOT NULL,
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDT_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_NO, GOODS_NO),
    CONSTRAINT CK_CART_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT FK_CART_USER FOREIGN KEY (USER_NO) REFERENCES user_info (USER_NO),
    CONSTRAINT FK_CART_GOODS FOREIGN KEY (GOODS_NO) REFERENCES goods_info (GOODS_NO)
);
